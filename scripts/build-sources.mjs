// Writes src/sources.ts: the text of every script, by its code key, for pages that show the code.
// Run after editing a script: node scripts/build-sources.mjs (a core test fails while it is stale).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("./src/", import.meta.url));
const out = {};
const walk = (dir) => {
  for (const f of readdirSync(dir).sort()) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/^v\d+\.ts$/.test(f)) out[relative(root, p).replace(/\.ts$/, "")] = readFileSync(p, "utf8");
  }
};
walk(root);
const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");
writeFileSync(join(root, "sources.ts"), `/** The text of every script, by its code key (generated by scripts/build-sources.mjs: do not edit). */\nexport const SOURCES: Readonly<Record<string, string>> = {\n${body}\n};\n`);
console.log(`${Object.keys(out).length} scripts`);
